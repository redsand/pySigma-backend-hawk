"""Rebuild rules/artex/ in the content repo from a checkout of the MalwareMustDie ARTEX pack.

    python import_artex_pack.py <pack_dir> [--out <content repo>/rules/artex]

<pack_dir> is etc/artex-stix-osquery-sigma-kql-snort-suricata-yara in
https://github.com/unixfreaxjp/malwaremustdie (DRL 1.1, author malwaremustdie.org - @unixfreaxjp).

The pack keeps correlations and the rules they count in different files; our converter takes one
file at a time. So every correlation is written into one file with the rules it names, and every
other rule into a file of its own. Rule text, ids, author and references are copied unchanged.
A rule our backend cannot convert (no HAWK source for it) is left out and listed in COVERAGE.md,
with every correlation that needs it; nothing is dropped silently. Rerun when the pack updates:
ids are the pack's, so the daily sync refreshes the same scores.
"""
import argparse
import datetime
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from score_filters import content_dir  # noqa: E402
from sigma.backends.hawk import hawkBackend  # noqa: E402
from sigma.collection import SigmaCollection  # noqa: E402
from sigma.pipelines.hawk import hawk_pipeline  # noqa: E402

PACK_URL = "https://github.com/unixfreaxjp/malwaremustdie/tree/master/etc/artex-stix-osquery-sigma-kql-snort-suricata-yara"
HEADER = ("# Source: MalwareMustDie ARTEX misuse detection pack %s, sigma/%s\n"
          "# " + PACK_URL + "\n"
          "# Author: malwaremustdie.org - @unixfreaxjp. License: Detection Rule License (DRL) 1.1,\n"
          "# https://github.com/SigmaHQ/Detection-Rule-License/blob/main/LICENSE.Detection.Rules.md\n"
          "# Generated by pySigma-backend-hawk converter_validation/import_artex_pack.py - do not edit;\n"
          "# rule text is the pack's, only regrouped so each correlation sits with the rules it counts.\n")
# What each pack logsource needs on the HAWK side, for the coverage table.
SOURCES = {
    "webserver": "HAWK WAF events (product_name Web Application Firewall)",
    "windows": "Windows agent (Sysmon process and file events)",
    "linux": "Linux process and file events (vendor_name Linux)",
    "dns": "any source that fills dns_query",
    "proxy": "web proxy logs (http_host)",
    "azure": "M365 collector (signInAudits / directoryAudits)",
    "aws": "AWS CloudTrail collector",
    "github": "GitHub audit log - no HAWK collector found; cannot fire until one exists",
    "kubernetes": "Kubernetes audit log - no HAWK collector found; cannot fire until one exists",
    "process_creation": "process events, Windows or Linux",
    "file_event": "file events, Windows or Linux",
}


def documents(pack: Path):
    """Every Sigma document in the pack as (raw text, parsed, relative file), in pack order."""
    out = []
    for path in sorted((pack / "sigma").rglob("*.yml")):
        text = path.read_text(encoding="utf-8")
        for raw in re.split(r"(?m)^---[ \t]*\r?\n", text):
            if not raw.strip():
                continue
            doc = yaml.safe_load(raw)
            if isinstance(doc, dict) and ("detection" in doc or "correlation" in doc):
                out.append((raw.rstrip() + "\n", doc, path.relative_to(pack / "sigma").as_posix()))
    return out


def convert(backend, texts):
    """Records for these documents as one file, or the error text."""
    try:
        return backend.convert(SigmaCollection.from_yaml("---\n".join(texts))), ""
    except Exception as e:  # noqa: BLE001 - the reason goes in COVERAGE.md
        return None, "%s: %s" % (type(e).__name__, str(e)[:200])


def source_of(doc):
    ls = doc.get("logsource") or {}
    key = ls.get("product") or ls.get("category") or "?"
    return SOURCES.get(key, key)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("pack")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    pack = Path(args.pack)
    out = Path(args.out) if args.out else content_dir() / "rules" / "artex"
    version = re.search(r"Version \*\*([0-9][^*]*)\*\*", (pack / "README.md").read_text(encoding="utf-8"))
    if not version:
        raise SystemExit("no pack version in %s" % (pack / "README.md"))
    version = "v" + version.group(1)
    docs = documents(pack)
    if not docs:
        raise SystemExit("no Sigma documents under %s" % (pack / "sigma"))
    backend = hawkBackend(processing_pipeline=hawk_pipeline())

    by_name = {}
    for raw, doc, rel in docs:
        name = doc.get("name")
        if not name or name in by_name:
            raise SystemExit("%s: rule without a unique name: %r" % (rel, doc.get("title")))
        by_name[name] = (raw, doc, rel)
    bases = {n: v for n, v in by_name.items() if "detection" in v[1]}
    corrs = {n: v for n, v in by_name.items() if "correlation" in v[1]}

    skipped = []  # (name, title, why)
    usable = {}
    for name, (raw, doc, rel) in bases.items():
        records, why = convert(backend, [raw])
        if records is None:
            skipped.append((name, doc.get("title", ""), why))
        else:
            usable[name] = (raw, doc, rel)

    # Group every correlation with the rules it counts; correlations sharing a rule share a file.
    group = {n: n for n in list(usable) + list(corrs)}

    def find(n):
        while group[n] != n:
            n = group[n]
        return n

    kept = {}
    for name, (raw, doc, rel) in corrs.items():
        needs = doc["correlation"]["rules"]
        lost = [n for n in needs if n not in usable]
        if lost:
            skipped.append((name, doc.get("title", ""), "needs %s, which is not converted" % ", ".join(lost)))
            continue
        records, why = convert(backend, [usable[n][0] for n in needs] + [raw])
        if records is None:
            skipped.append((name, doc.get("title", ""), why))
            continue
        kept[name] = (raw, doc, rel)
        for n in needs:
            group[find(n)] = find(name)

    files = {}
    for name in list(usable) + list(kept):
        files.setdefault(find(name), []).append(name)
    # The backend emits a correlation's score but not the rules it counts. A counted rule the pack
    # rates medium or above (a web server spawning a shell) is an alert in its own right, so it
    # also gets a file of its own. Low ones are the pack's "never act on this alone" building blocks.
    for root, names in list(files.items()):
        for n in names:
            if n in usable and len(names) > 1 and usable[n][1].get("level") in ("medium", "high", "critical"):
                files[n + "_alone"] = [n]

    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("mmd_artex_*.yml"):
        old.unlink()
    rows = []
    for root, names in sorted(files.items()):
        members = [n for n in names if n in usable] + [n for n in names if n in kept]
        texts = [(usable.get(n) or kept[n])[0] for n in members]
        records, why = convert(backend, texts)
        if records is None:
            raise SystemExit("%s converted alone but not together: %s" % (root, why))
        rels = sorted({(usable.get(n) or kept[n])[2] for n in members})
        (out / (root + ".yml")).write_text(HEADER % (version, ", sigma/".join(rels)) + "---\n".join(texts),
                                           encoding="utf-8", newline="\n")
        for n in members:
            doc = (usable.get(n) or kept[n])[1]
            c = doc.get("correlation")
            if not c and len(members) > 1 and (n + "_alone" in files or doc.get("level") == "low"):
                continue  # counted inside a correlation: listed under its own file, or never a score
            rows.append((root + ".yml", doc.get("title", ""), doc.get("level", ""),
                         "%s; counts %s" % (source_of(usable[c["rules"][0]][1]), ", ".join(c["rules"])) if c
                         else source_of(doc)))

    md = ["# ARTEX pack coverage in HAWK", "",
          "Generated %s from pack %s by `import_artex_pack.py`. %d rules in %d files; %d left out." % (
              datetime.date.today().isoformat(), version, len(rows), len(files), len(skipped)), "",
          "A rule listed here converts; whether it can fire depends on the source in the last column",
          "being collected for that customer. All import disabled.", "",
          "| File | Rule | Level | Needs |", "|---|---|---|---|"]
    md += ["| `%s` | %s | %s | %s |" % r for r in rows]
    md += ["", "## Left out (not converted)", "", "| Rule | Why |", "|---|---|"]
    md += ["| %s (`%s`) | %s |" % (t, n, w.replace("|", "/")) for n, t, w in skipped]
    (out / "COVERAGE.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("pack %s: %d rules in %d files -> %s; %d left out" % (version, len(rows), len(files), out, len(skipped)))
    for n, t, w in skipped:
        print("  left out: %s - %s" % (n, w))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
