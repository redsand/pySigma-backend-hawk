"""Regenerate the HAWK firmware BYOVD "known vulnerable build" Sigma rule from the driver feed.

The hawkvttac agent raises byovd_driver_loaded when a loaded driver's file NAME is on the
LOLDrivers list. A name alone is not a vulnerability: the same name is the fixed build on most
hosts (Realtek RtsPer.sys, Dell DellInstrumentation.sys, Windows csc.sys / afd.sys). This rule
matches only when the driver's SHA-256 is one of the feed's KnownVulnerableSamples - the same
set agents from hawkagentd 4f1611c use to grade a finding "confirmed".

Usage:
    python gen_byovd_known_builds.py                 # fetch the feed, write the rule
    python gen_byovd_known_builds.py --feed drivers.json
"""
import argparse
import datetime
import json
import os
from pathlib import Path

import requests
import urllib3

urllib3.disable_warnings()
FEED_PRIMARY = "https://downloads.hawkdefense.com/resources/analytics/threat-intelligence/drivers.json"
FEED_BACKUP = "https://www.loldrivers.io/api/drivers.json"
RULE_ID = "6c1f4b8e-2d7a-4e93-9b5c-8a0e3f71d2c4"
RULES_REPO = Path(os.environ.get("HAWK_SIGMA_RULES") or Path(__file__).resolve().parents[2] / "hawk-sigma-rules")
OUT = RULES_REPO / "rules" / "firmware" / "hawk_firmware_byovd_known_vulnerable_build.yml"

HEADER = """title: HAWK - Known Vulnerable Or Malicious Driver Build Loaded (BYOVD)
id: {rid}
status: test
description: |
    The HAWK agent firmware monitor reported a loaded driver whose SHA-256 is a known vulnerable or
    malicious build in the LOLDrivers feed (KnownVulnerableSamples). The agent's byovd_driver_loaded
    finding fires on the driver file NAME, which on most hosts is the fixed vendor build; only a hash
    match confirms the vulnerable build. Generated by pySigma-backend-hawk
    converter_validation/gen_byovd_known_builds.py from the feed on {day} ({n} hashes).
references:
    - https://www.loldrivers.io/
author: HAWK Defense
date: 2026-10-21
modified: {day}
tags:
    - attack.privilege-escalation
    - attack.defense-evasion
    - attack.t1068
    - attack.t1562.001
logsource:
    product: hawk
    service: firmware
detection:
    selection_finding:
        threat_name: 'byovd_driver_loaded'
    selection_hash:
        file_hash_sha256:
"""
FOOTER = """    condition: all of selection_*
falsepositives:
    - An outdated hardware utility or anti-cheat driver that still ships the vulnerable build (still worth removing)
level: critical
"""


def load_feed(path: str | None) -> list:
    if path:
        return json.load(open(path, encoding="utf-8"))
    for url in (FEED_PRIMARY, FEED_BACKUP):
        r = requests.get(url, timeout=120, verify=False)
        if r.status_code == 200 and r.content:
            return r.json()
    raise SystemExit("driver feed unavailable")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--feed")
    args = ap.parse_args()
    hashes = set()
    for drv in load_feed(args.feed):
        for s in drv.get("KnownVulnerableSamples") or []:
            h = str(s.get("SHA256") or "").lower()
            if len(h) == 64 and all(c in "0123456789abcdef" for c in h):
                hashes.add(h)
    if len(hashes) < 1000:  # a truncated feed must never shrink the rule
        raise SystemExit(f"only {len(hashes)} hashes in the feed; refusing to write")
    day = datetime.date.today().isoformat()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = HEADER.format(rid=RULE_ID, day=day, n=len(hashes))
    body += "".join(f"            - '{h}'\n" for h in sorted(hashes)) + FOOTER
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(hashes)} hashes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
